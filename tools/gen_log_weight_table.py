#!/usr/bin/env python3
import hashlib
import json
import pathlib
import re
import struct
import subprocess
import sys

if len(sys.argv) < 3 or sys.argv[1] not in ("--write", "--check"):
    raise SystemExit(
        "usage: gen_log_weight_table.py --write|--check GENERATOR [ARGS...]"
    )

root = pathlib.Path(__file__).resolve().parents[1]
result = subprocess.run(
    sys.argv[2:], check=True, stdout=subprocess.PIPE
).stdout.decode("ascii")
lines = result.splitlines()
if len(lines) != 1024 or any(
    not re.fullmatch(r"[0-9a-f]{8}", x) for x in lines
):
    raise SystemExit("generator did not emit exactly 1024 hexadecimal words")

words = [int(x, 16) for x in lines]
if words[0] != 0x3f800000:
    raise SystemExit("T[0] must encode 1.0")
if any(not 0x3f800000 <= x < 0x40000000 for x in words):
    raise SystemExit("table entry outside [1,2)")
if any(a >= b for a, b in zip(words, words[1:])):
    raise SystemExit("table is not strictly increasing")

raw = struct.pack("<1024I", *words)
digest = hashlib.sha256(raw).hexdigest()

header = (
    "#pragma once\n"
    "// Generated by tools/gen_log_weight_table.py; do not edit.\n"
    "#include <cstdint>\n"
    "namespace logweight {\n"
    "inline constexpr int kDecoderVersion = 2;\n"
    "inline constexpr int kTableVersion = 1;\n"
    f'inline constexpr char kTableSha256[] = "{digest}";\n'
    "inline constexpr std::uint32_t kTable[1024] = {\n"
)
for i in range(0, 1024, 8):
    header += "    " + ", ".join(
        f"0x{x:08x}u" for x in words[i:i + 8]
    ) + ",\n"
header += "};\n} // namespace logweight\n"

identity = json.dumps({
    "decoderVersion": 2,
    "tableVersion": 1,
    "entries": 1024,
    "hashEncoding": "1024 uint32 words, little endian, no prefix",
    "sha256": digest,
    "law": (
        "bits32(evomath::expf("
        "(float32(r)*0x1p-10f)*0x1.62e43p-1f)), r=0..1023"
    ),
}, indent=2, sort_keys=True) + "\n"

outputs = {
    root / "src/core/weight_log_table.hpp": header.encode("ascii"),
    root / "src/core/weight_log_table.identity.json":
        identity.encode("ascii"),
}

for path, expected in outputs.items():
    if sys.argv[1] == "--write":
        path.write_bytes(expected)
    elif not path.is_file() or path.read_bytes() != expected:
        raise SystemExit(f"generated identity mismatch: {path}")

print(digest)
